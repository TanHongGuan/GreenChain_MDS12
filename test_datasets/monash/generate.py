"""Generate the Monash University Malaysia test workbooks.

SYNTHETIC DATA. These are not real meter readings, bills or emissions
statements for Monash University Malaysia or any of its buildings. Every figure
here is generated by this script from a fixed seed, and every workbook says so
on its own 00_Read_Me sheet. The buildings and the campus are named so the test
data reads like something an uploader would recognise, nothing more.

Run:  python test_datasets/monash/generate.py

The two buildings are deliberately written in different house styles, because a
real platform receives files from whoever produced them:

                        Engineering                 Pharmacy
  electricity     daily kWh, DD/MM/YYYY       daily MWh, MM/DD/YYYY
  water           cumulative m3, YYYY-MM-DD   daily litres, YYYY/MM/DD
  carbon          monthly tCO2e, YYYY-MM      monthly kgCO2e, YYYY-MM

Between them they exercise every unit conversion the importer performs, all
three aggregation rules, and all three date orders it has to resolve.
"""

from __future__ import annotations

import csv
import random
from calendar import monthrange
from datetime import date
from decimal import Decimal
from pathlib import Path

from openpyxl import Workbook

HERE = Path(__file__).resolve().parent
EXPECTED = HERE / "expected"
YEAR = 2026
QUARTERS = {"Q1": (1, 2, 3), "Q2": (4, 5, 6), "Q3": (7, 8, 9), "Q4": (10, 11, 12)}

CLASSIFICATION = "SYNTHETIC - generated test data, NOT real meter readings or statements"
CAMPUS = "Monash University Malaysia, Bandar Sunway, Selangor"

# Teaching load drives consumption on a campus: the long break either side of the
# new year and the mid-year break are quiet, exam and peak-teaching months are not.
TEACHING_LOAD = {1: 0.74, 2: 0.98, 3: 1.06, 4: 1.08, 5: 1.05, 6: 0.86,
                 7: 0.92, 8: 1.04, 9: 1.07, 10: 1.09, 11: 0.99, 12: 0.70}

# Peninsular Malaysia grid emission factor, tCO2e per MWh. Published by the Energy
# Commission (Suruhanjaya Tenaga) in the Grid Emission Factor study; 0.585 is the
# figure these fixtures assume. Carbon is still *reported* per month rather than
# derived by the importer, which is how the real registers work.
GRID_FACTOR = Decimal("0.585")


def days_in(months: tuple[int, ...]) -> list[date]:
    return [date(YEAR, month, day)
            for month in months
            for day in range(1, monthrange(YEAR, month)[1] + 1)]


def daily_series(rng: random.Random, days: list[date], weekday_base: float) -> list[Decimal]:
    """One value per day, varying with the teaching calendar and the weekend."""
    values = []
    for day in days:
        load = TEACHING_LOAD[day.month]
        weekend = 0.58 if day.weekday() >= 5 else 1.0
        jitter = rng.uniform(0.94, 1.06)
        values.append(Decimal(f"{weekday_base * load * weekend * jitter:.2f}"))
    return values


def read_me(book: Workbook, rows: list[tuple[str, str]]) -> None:
    sheet = book.create_sheet("00_Read_Me")
    sheet.append(["Key", "Value"])
    for key, value in rows:
        sheet.append([key, value])


def rules(book: Workbook, rows: list[tuple[str, str]]) -> None:
    # Keys are written as prose rather than as codes ("GRID-A"), because the
    # importer's note extraction drops identifier-shaped tokens before the sheet
    # reaches the model, which would leave each rule without its subject.
    sheet = book.create_sheet("Meter_And_ETL_Rules")
    sheet.append(["Source field / meter", "Interpretation / action"])
    for key, value in rows:
        sheet.append([key, value])


def engineering(quarter: str, rng: random.Random, opening: Decimal,
                scenario: str, note: str) -> tuple[Workbook, dict, Decimal]:
    """Daily kWh, a cumulative water meter, and monthly reported carbon."""
    months = QUARTERS[quarter]
    days = days_in(months)
    electricity = daily_series(rng, days, 5_820.0)
    water_daily = daily_series(rng, days, 23.4)

    book = Workbook()
    power = book.active
    power.title = "Electricity_Daily"
    power.append(["Reading Date (DD/MM/YYYY)", "Main Incoming Supply (kWh)", "Chiller Plant Submeter (kWh)",
                  "Meter Point", "Notes"])
    for day, value in zip(days, electricity):
        # The submeter is a share of the main supply, never an addition to it.
        power.append([day.strftime("%d/%m/%Y"), str(value), str((value * Decimal("0.31")).quantize(Decimal("0.01"))),
                      "ENG-MAIN", "Main supply INCLUDES the chiller submeter"])

    water = book.create_sheet("Water_Meter")
    water.append(["Reading Date", "Bulk Meter - cumulative (m3)", "Meter Serial", "Remarks"])
    running = opening
    for day, value in zip(days, water_daily):
        running += value
        water.append([day.strftime("%Y-%m-%d"), str(running), "ENG-WTR-01",
                      "Cumulative reading, not daily usage"])

    carbon = book.create_sheet("Carbon_Monthly")
    carbon.append(["Month", "Reported Scope 2 Emissions (tCO2e)", "Reported Scope 1 Emissions (tCO2e)",
                   "Reporting Basis", "Statement Ref"])
    scope2, scope1 = {}, {}
    for month in months:
        month_kwh = sum(value for day, value in zip(days, electricity) if day.month == month)
        two = ((month_kwh / 1000) * GRID_FACTOR).quantize(Decimal("0.001"))
        one = (two * Decimal("0.042")).quantize(Decimal("0.001"))
        scope2[month], scope1[month] = two, one
        carbon.append([f"{YEAR}-{month:02d}", str(two), str(one),
                       "Reported totals, not derived by GreenChain", f"ENG-GHG-{YEAR}{month:02d}"])

    read_me(book, [
        ("Dataset", f"Monash Engineering Building {YEAR}-{quarter}"),
        ("Scenario", scenario),
        ("Organisation", "Monash University Malaysia"),
        ("Building", "Engineering Building"),
        ("Building ID", "Engineering Building, Jalan Lagoon Selatan"),
        ("Campus", CAMPUS),
        ("Reporting period", f"{YEAR}-{quarter}"),
        ("Data classification", CLASSIFICATION),
        ("Scope", "Building-level operational electricity, water and reported CO2-equivalent emissions"),
        ("Notes", note),
    ])
    rules(book, [
        ("Main Incoming Supply (kWh)", "Daily consumption on the building intake; sum the days for a month"),
        ("Chiller Plant Submeter (kWh)", "Already included in the main supply; DO NOT ADD"),
        ("Bulk Meter - cumulative (m3)", "Cumulative reading; a month's usage is the rise across it"),
        ("Water meter reading before this quarter", str(opening)),
        ("Reported Scope 2 Emissions (tCO2e)", "Add to Scope 1 for the building total; do not derive from electricity"),
        ("Date parsing", "Electricity DD/MM/YYYY, water YYYY-MM-DD, carbon YYYY-MM"),
    ])

    totals = {
        "electricity_kwh": sum(electricity),
        "water_m3": running - opening,
        "co2_tco2e": sum(scope2.values()) + sum(scope1.values()),
    }
    return book, totals, running


def pharmacy(quarter: str, rng: random.Random) -> tuple[Workbook, dict]:
    """Daily MWh, daily litres, and monthly reported carbon in kilograms."""
    months = QUARTERS[quarter]
    days = days_in(months)
    electricity_mwh = [Decimal(f"{float(value) / 1000:.4f}") for value in daily_series(rng, days, 3_940.0)]
    water_litres = [Decimal(f"{float(value):.0f}") for value in daily_series(rng, days, 15_300.0)]

    book = Workbook()
    power = book.active
    power.title = "Electricity_Consumption"
    power.append(["Usage Date (MM/DD/YYYY)", "Metered Consumption (MWh)", "Tariff Code", "Invoice Reference"])
    for day, value in zip(days, electricity_mwh):
        power.append([day.strftime("%m/%d/%Y"), str(value), "C1 Commercial",
                      f"PHA-EL-{YEAR}{day.month:02d}"])

    water = book.create_sheet("Water_Invoices")
    water.append(["Date Recorded", "Water Consumed (Litres)", "Service Area", "Bill Number"])
    for day, value in zip(days, water_litres):
        water.append([day.strftime("%Y/%m/%d"), str(value), "Whole building",
                      f"PHA-WT-{YEAR}{day.month:02d}"])

    carbon = book.create_sheet("Emissions_Register")
    carbon.append(["Reporting Month", "Reported Emissions (kgCO2e)", "Basis", "Register Ref"])
    monthly_carbon = {}
    for month in months:
        month_mwh = sum(value for day, value in zip(days, electricity_mwh) if day.month == month)
        kilograms = (month_mwh * GRID_FACTOR * 1000 * Decimal("1.035")).quantize(Decimal("0.01"))
        monthly_carbon[month] = kilograms
        carbon.append([f"{YEAR}-{month:02d}", str(kilograms),
                       "Reported operational total", f"PHA-GHG-{YEAR}{month:02d}"])

    read_me(book, [
        ("Dataset", f"Monash Pharmacy Building {YEAR}-{quarter}"),
        ("Scenario", "VALID"),
        ("Organisation", "Monash University Malaysia"),
        ("Building", "Pharmacy Building"),
        ("Building ID", "Pharmacy Building, Jalan Lagoon Selatan"),
        ("Campus", CAMPUS),
        ("Reporting period", f"{YEAR}-{quarter}"),
        ("Data classification", CLASSIFICATION),
        ("Scope", "Building-level operational electricity, water and reported CO2-equivalent emissions"),
        ("Notes", "Expected to pass all data checks"),
    ])
    rules(book, [
        ("Metered Consumption (MWh)", "Daily consumption in megawatt-hours; multiply by 1,000 for kWh"),
        ("Water Consumed (Litres)", "Daily volume in litres; divide by 1,000 for m3"),
        ("Reported Emissions (kgCO2e)", "Reported monthly total in kilograms; divide by 1,000 for tCO2e"),
        ("Date parsing", "Electricity MM/DD/YYYY, water YYYY/MM/DD, emissions YYYY-MM"),
    ])

    totals = {
        "electricity_kwh": sum(electricity_mwh) * 1000,
        "water_m3": sum(water_litres) / 1000,
        "co2_tco2e": sum(monthly_carbon.values()) / 1000,
    }
    return book, totals


def break_it(book: Workbook) -> list[tuple[str, str, str, str]]:
    """Plant three faults a correct importer must find, and say where they are.

    Only cells are damaged, never whole rows: a blank row is skipped as padding,
    so blanking one would remove the fault rather than create it.
    """
    faults = []

    # The importer reports a fault against the row's date normalised to ISO, so
    # the expected list is written the same way rather than in the sheet's own
    # format - otherwise the two could never be compared.
    def day_first(cell_value: str) -> str:
        day, month, year = (int(part) for part in str(cell_value).split("/"))
        return date(year, month, day).isoformat()

    power = book["Electricity_Daily"]
    row = 20  # the 19th reading
    power.cell(row=row, column=2, value="N/A")
    faults.append(("Electricity_Daily", day_first(power.cell(row=row, column=1).value),
                   "Main Incoming Supply (kWh)", "INVALID_NUMERIC"))

    row = 48
    # Assigning through .value: Worksheet.cell(value=None) leaves the cell alone,
    # so passing None there silently fails to create the blank.
    power.cell(row=row, column=2).value = None
    faults.append(("Electricity_Daily", day_first(power.cell(row=row, column=1).value),
                   "Main Incoming Supply (kWh)", "MISSING_VALUE"))

    water = book["Water_Meter"]
    row = 41
    previous = Decimal(str(water.cell(row=row - 1, column=2).value))
    water.cell(row=row, column=2, value=str(previous - Decimal("86.40")))
    faults.append(("Water_Meter", str(water.cell(row=row, column=1).value),
                   "Bulk Meter - cumulative (m3)", "DECREASING_CUMULATIVE"))

    return faults


def write_expected(name: str, building_id: str, period: str, totals: dict) -> None:
    with (EXPECTED / f"{name}_expected_quarterly.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["building_id", "period", "electricity_kwh", "water_m3", "co2_tco2e"])
        writer.writerow([building_id, period,
                         totals["electricity_kwh"], totals["water_m3"], totals["co2_tco2e"]])


def main() -> None:
    HERE.mkdir(parents=True, exist_ok=True)
    EXPECTED.mkdir(parents=True, exist_ok=True)

    # The Engineering water meter runs continuously through the year, so each
    # quarter opens on the reading the previous quarter closed with. Q1 opens on
    # the reading taken at the end of the previous December.
    opening = Decimal("41820.60")
    for quarter in QUARTERS:
        rng = random.Random(f"eng-{quarter}")
        scenario = "VALID - intended for auditor approval" if quarter == "Q1" else "VALID"
        note = ("First submission for the quarter; approve this one to see an approved series"
                if quarter == "Q1" else "Expected to pass all data checks")
        book, totals, closing = engineering(quarter, rng, opening, scenario, note)
        name = f"MUM_ENG_{YEAR}_{quarter}" + ("_APPROVED" if quarter == "Q1" else "_VALID")
        book.save(HERE / f"{name}.xlsx")
        write_expected(name, "Engineering Building", f"{YEAR}-{quarter}", totals)

        if quarter == "Q1":
            # A second, independent submission for the same quarter: the meters
            # were re-read after a billing query, so the figures differ slightly.
            # Leave this one unreviewed to exercise the approved/unreviewed filter.
            revised_rng = random.Random("eng-Q1-revised")
            revised, revised_totals, _ = engineering(
                quarter, revised_rng, opening, "VALID - leave unreviewed",
                "Re-read after a billing query. Upload second and leave unreviewed.")
            revised.save(HERE / f"MUM_ENG_{YEAR}_Q1_UNREVIEWED.xlsx")
            write_expected(f"MUM_ENG_{YEAR}_Q1_UNREVIEWED", "Engineering Building",
                           f"{YEAR}-{quarter}", revised_totals)

            broken_rng = random.Random("eng-Q1-invalid")
            broken, _, _ = engineering(quarter, broken_rng, opening, "INVALID",
                                       "Contains deliberate faults; must be refused, not published.")
            faults = break_it(broken)
            broken.save(HERE / f"MUM_ENG_{YEAR}_Q1_INVALID.xlsx")
            with (EXPECTED / f"MUM_ENG_{YEAR}_Q1_INVALID_expected_errors.csv").open(
                    "w", newline="", encoding="utf-8") as handle:
                writer = csv.writer(handle)
                writer.writerow(["severity", "sheet", "row_date", "field", "error_code", "expected_handling"])
                for sheet, row_date, field, code in faults:
                    writer.writerow(["ERROR", sheet, row_date, field, code,
                                     "Refuse the upload; publish nothing"])

        opening = closing

    for quarter in QUARTERS:
        rng = random.Random(f"pha-{quarter}")
        book, totals = pharmacy(quarter, rng)
        name = f"MUM_PHA_{YEAR}_{quarter}_VALID"
        book.save(HERE / f"{name}.xlsx")
        write_expected(name, "Pharmacy Building", f"{YEAR}-{quarter}", totals)

    print(f"Wrote {len(list(HERE.glob('*.xlsx')))} workbooks to {HERE}")


if __name__ == "__main__":
    main()
